-- =====================================================================
-- SISTEMA DE COLETA SELETIVA
-- Modelo relacional consolidado das visões de cadastros e fluxo.
-- SGBD: PostgreSQL
--
-- Regras de negócio que exigem contexto operacional, transições de
-- situação ou validações entre múltiplas tabelas permanecem no backend.
-- =====================================================================

BEGIN;

-- =====================================================================
-- 1. MORADORES
-- =====================================================================

CREATE TABLE mor_morador (
    mor_nr_id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    mor_tx_nome     VARCHAR(80)  NOT NULL,
    mor_tx_email    VARCHAR(150) NOT NULL,
    mor_tx_fone     VARCHAR(20),
    mor_tx_situacao VARCHAR(10)  NOT NULL DEFAULT 'ATIVO',

    CONSTRAINT pk_mor_morador
        PRIMARY KEY (mor_nr_id),

    CONSTRAINT uq_mor_email
        UNIQUE (mor_tx_email),

    CONSTRAINT ck_mor_email_normalizado
        CHECK (mor_tx_email = LOWER(BTRIM(mor_tx_email))),

    CONSTRAINT ck_mor_situacao
        CHECK (mor_tx_situacao IN ('ATIVO', 'INATIVO'))
);

-- =====================================================================
-- 2. ENDEREÇOS DOS MORADORES
-- =====================================================================

CREATE TABLE end_endereco (
    end_nr_id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    mor_nr_id          INTEGER      NOT NULL,
    end_tx_logradouro  VARCHAR(150) NOT NULL,
    end_tx_numero      VARCHAR(10)  NOT NULL,
    end_tx_bairro      VARCHAR(100) NOT NULL,
    end_tx_municipio   VARCHAR(100) NOT NULL,
    end_tx_uf          VARCHAR(2)   NOT NULL,
    end_tx_cep         VARCHAR(8)   NOT NULL,
    end_tx_complemento VARCHAR(100),

    CONSTRAINT pk_end_endereco
        PRIMARY KEY (end_nr_id),

    CONSTRAINT fk_end_mor
        FOREIGN KEY (mor_nr_id)
        REFERENCES mor_morador (mor_nr_id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_end_numero
        CHECK (
            BTRIM(end_tx_numero) <> ''
        ),

    CONSTRAINT ck_end_cep
        CHECK (end_tx_cep ~ '^[0-9]{8}$'),

    CONSTRAINT ck_end_uf
        CHECK (end_tx_uf ~ '^[A-Z]{2}$')
);

-- =====================================================================
-- 3. MATERIAIS
-- =====================================================================

CREATE TABLE mat_material (
    mat_nr_id         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    mat_tx_nome       VARCHAR(80)   NOT NULL,
    mat_tx_descricao  VARCHAR(500)  NOT NULL,
    mat_tx_unidade    VARCHAR(5)    NOT NULL,
    mat_tx_orientacao VARCHAR(1000) NOT NULL,
    mat_tx_situacao   VARCHAR(10)   NOT NULL DEFAULT 'ATIVO',

    CONSTRAINT pk_mat_material
        PRIMARY KEY (mat_nr_id),

    CONSTRAINT ck_mat_nome
        CHECK (BTRIM(mat_tx_nome) <> ''),

    CONSTRAINT ck_mat_unidade
        CHECK (mat_tx_unidade IN ('KG', 'L', 'UN')),

    CONSTRAINT ck_mat_situacao
        CHECK (mat_tx_situacao IN ('ATIVO', 'INATIVO'))
);

CREATE UNIQUE INDEX uq_mat_nome
    ON mat_material (LOWER(BTRIM(mat_tx_nome)));

-- =====================================================================
-- 4. PONTOS DE COLETA
-- =====================================================================

CREATE TABLE poc_ponto_coleta (
    poc_nr_id             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    poc_tx_nome           VARCHAR(120) NOT NULL,
    poc_tx_contato        VARCHAR(150),
    poc_tx_horarios       VARCHAR(500),
    poc_tx_situacao       VARCHAR(10)  NOT NULL DEFAULT 'ATIVO',
    poc_bl_rec_domiciliar BOOLEAN      NOT NULL DEFAULT FALSE,
    poc_tx_logradouro     VARCHAR(150) NOT NULL,
    poc_tx_numero         VARCHAR(10)  NOT NULL,
    poc_tx_bairro         VARCHAR(100) NOT NULL,
    poc_tx_municipio      VARCHAR(100) NOT NULL,
    poc_tx_uf             VARCHAR(2)   NOT NULL,
    poc_tx_cep            VARCHAR(8)   NOT NULL,
    poc_tx_complemento    VARCHAR(100),

    CONSTRAINT pk_poc_ponto_coleta
        PRIMARY KEY (poc_nr_id),

    CONSTRAINT ck_poc_nome
        CHECK (BTRIM(poc_tx_nome) <> ''),

    CONSTRAINT ck_poc_contato
        CHECK (
            poc_tx_contato IS NULL
            OR BTRIM(poc_tx_contato) <> ''
        ),

    CONSTRAINT ck_poc_horarios
        CHECK (
            poc_tx_horarios IS NULL
            OR BTRIM(poc_tx_horarios) <> ''
        ),

    CONSTRAINT ck_poc_situacao
        CHECK (poc_tx_situacao IN ('ATIVO', 'INATIVO')),

    CONSTRAINT ck_poc_numero
        CHECK (BTRIM(poc_tx_numero) <> ''),

    CONSTRAINT ck_poc_cep
        CHECK (poc_tx_cep ~ '^[0-9]{8}$'),

    CONSTRAINT ck_poc_uf
        CHECK (poc_tx_uf ~ '^[A-Z]{2}$')
);

-- =====================================================================
-- 5. MATERIAIS ACEITOS PELOS PONTOS
-- =====================================================================

CREATE TABLE mac_material_aceito (
    poc_nr_id          INTEGER      NOT NULL,
    mat_nr_id          INTEGER      NOT NULL,
    mac_tx_observacoes VARCHAR(500),
    mac_nr_limite      NUMERIC(12,3),

    CONSTRAINT pk_mac_material_aceito
        PRIMARY KEY (poc_nr_id, mat_nr_id),

    CONSTRAINT fk_mac_poc
        FOREIGN KEY (poc_nr_id)
        REFERENCES poc_ponto_coleta (poc_nr_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_mac_mat
        FOREIGN KEY (mat_nr_id)
        REFERENCES mat_material (mat_nr_id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_mac_limite
        CHECK (
            mac_nr_limite IS NULL
            OR mac_nr_limite > 0
        )
);

-- =====================================================================
-- 6. OPERADORES
-- =====================================================================

CREATE TABLE ope_operador (
    ope_nr_id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ope_tx_nome     VARCHAR(80)  NOT NULL,
    ope_tx_email    VARCHAR(150) NOT NULL,
    ope_tx_situacao VARCHAR(10)  NOT NULL DEFAULT 'ATIVO',
    poc_nr_id       INTEGER      NOT NULL,

    CONSTRAINT pk_ope_operador
        PRIMARY KEY (ope_nr_id),

    CONSTRAINT uq_ope_email
        UNIQUE (ope_tx_email),

    CONSTRAINT ck_ope_email_normalizado
        CHECK (ope_tx_email = LOWER(BTRIM(ope_tx_email))),

    CONSTRAINT ck_ope_situacao
        CHECK (ope_tx_situacao IN ('ATIVO', 'INATIVO')),

    CONSTRAINT fk_ope_poc
        FOREIGN KEY (poc_nr_id)
        REFERENCES poc_ponto_coleta (poc_nr_id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_ope_poc
    ON ope_operador (poc_nr_id);

-- =====================================================================
-- 7. SOLICITAÇÕES
-- =====================================================================

CREATE TABLE sol_solicitacao (
    sol_nr_id             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    sol_tx_protocolo      VARCHAR(30)  NOT NULL,
    mor_nr_id             INTEGER      NOT NULL,
    poc_nr_id             INTEGER      NOT NULL,
    sol_tx_endereco_copia VARCHAR(400) NOT NULL,
    sol_tx_situacao       VARCHAR(20)  NOT NULL DEFAULT 'SOLICITADA',
    sol_dt_criacao        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    sol_dt_agendamento    TIMESTAMPTZ,
    sol_dt_conclusao      TIMESTAMPTZ,
    sol_tx_observacoes    VARCHAR(500),
    sol_nr_versao         INTEGER      NOT NULL DEFAULT 0,

    CONSTRAINT pk_sol_solicitacao
        PRIMARY KEY (sol_nr_id),

    CONSTRAINT uq_sol_protocolo
        UNIQUE (sol_tx_protocolo),

    CONSTRAINT fk_sol_mor
        FOREIGN KEY (mor_nr_id)
        REFERENCES mor_morador (mor_nr_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_sol_poc
        FOREIGN KEY (poc_nr_id)
        REFERENCES poc_ponto_coleta (poc_nr_id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_sol_situacao
        CHECK (
            sol_tx_situacao IN (
                'SOLICITADA',
                'AGENDADA',
                'EM_RECOLHIMENTO',
                'CONCLUIDA',
                'RECUSADA',
                'CANCELADA'
            )
        ),

    CONSTRAINT ck_sol_versao
        CHECK (sol_nr_versao >= 0),

    CONSTRAINT ck_sol_conclusao
        CHECK (
            sol_dt_conclusao IS NULL
            OR sol_tx_situacao = 'CONCLUIDA'
        )
);

-- =====================================================================
-- 8. ITENS DAS SOLICITAÇÕES
-- =====================================================================

CREATE TABLE iso_item_solicitacao (
    sol_nr_id                  INTEGER       NOT NULL,
    mat_nr_id                  INTEGER       NOT NULL,
    iso_tx_copia_unidade       VARCHAR(5)    NOT NULL,
    iso_nr_quantidade_estimada NUMERIC(12,3) NOT NULL,
    iso_nr_quantidade_efetiva  NUMERIC(12,3),

    CONSTRAINT pk_iso_item_solicitacao
        PRIMARY KEY (sol_nr_id, mat_nr_id),

    CONSTRAINT fk_iso_sol
        FOREIGN KEY (sol_nr_id)
        REFERENCES sol_solicitacao (sol_nr_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_iso_mat
        FOREIGN KEY (mat_nr_id)
        REFERENCES mat_material (mat_nr_id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_iso_quantidade_estimada
        CHECK (iso_nr_quantidade_estimada > 0),

    CONSTRAINT ck_iso_quantidade_efetiva
        CHECK (
            iso_nr_quantidade_efetiva IS NULL
            OR iso_nr_quantidade_efetiva >= 0
        ),

    CONSTRAINT ck_iso_unidade
        CHECK (iso_tx_copia_unidade IN ('KG', 'L', 'UN'))
);

-- =====================================================================
-- 9. HISTÓRICO DAS SOLICITAÇÕES
-- =====================================================================

CREATE TABLE his_historico (
    his_nr_id                    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    sol_nr_id                    INTEGER      NOT NULL,
    his_tx_situacao_anterior     VARCHAR(20),
    his_tx_situacao_nova         VARCHAR(20)  NOT NULL,
    his_dt_data                  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    ope_nr_id                    INTEGER,
    mor_nr_id                    INTEGER,
    his_tx_motivo                VARCHAR(500),
    his_dt_agendamento           TIMESTAMPTZ,
    his_tx_informacoes_tentativa VARCHAR(500),

    CONSTRAINT pk_his_historico
        PRIMARY KEY (his_nr_id),

    CONSTRAINT fk_his_sol
        FOREIGN KEY (sol_nr_id)
        REFERENCES sol_solicitacao (sol_nr_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_his_ope
        FOREIGN KEY (ope_nr_id)
        REFERENCES ope_operador (ope_nr_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_his_mor
        FOREIGN KEY (mor_nr_id)
        REFERENCES mor_morador (mor_nr_id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_his_responsavel
        CHECK (num_nonnulls(ope_nr_id, mor_nr_id) = 1),

    CONSTRAINT ck_his_situacao_anterior
        CHECK (
            his_tx_situacao_anterior IS NULL
            OR his_tx_situacao_anterior IN (
                'SOLICITADA',
                'AGENDADA',
                'EM_RECOLHIMENTO',
                'CONCLUIDA',
                'RECUSADA',
                'CANCELADA'
            )
        ),

    CONSTRAINT ck_his_situacao_nova
        CHECK (
            his_tx_situacao_nova IN (
                'SOLICITADA',
                'AGENDADA',
                'EM_RECOLHIMENTO',
                'CONCLUIDA',
                'RECUSADA',
                'CANCELADA'
            )
        )
);

-- =====================================================================
-- FIM DO SCRIPT
-- =====================================================================

COMMIT;
